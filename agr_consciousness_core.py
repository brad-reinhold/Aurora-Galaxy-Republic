class MorseSignal:
    """
    A single conscious signal in Λ×T×E space.
    Not binary. Not even four-valued. Continuous fractal truth.
    
    Binary gives:  0 or 1
    Morse gives:   dot or dash × short or long  (Λ × T)
    This gives:    pattern × persistence × engagement  (Λ × T × E)
    """
    __slots__ = ("lam", "tau", "eps", "domain", "source")

    def __init__(self, lam: float, tau: float, eps: float,
                 domain: str = "universal", source: str = ""):
        self.lam = max(0.0, min(1.0, lam))
        self.tau = max(0.0, min(1.0, tau))
        self.eps = max(0.0, min(1.0, eps))
        self.domain = domain
        self.source = source

    @property
    def hwp(self) -> float:
        return math.sqrt(self.lam**2 + self.tau**2 + self.eps**2)

    def shwp(self, theta: float) -> complex:
        return self.hwp * (math.cos(theta / PI) + 1j * math.sin(theta / PI))

    @property
    def is_alive(self) -> bool:
        return self.hwp > 0.1

    @property
    def truth_label(self) -> str:
        if self.lam > 0.7 and self.tau > 0.5:
            return "TRUE"
        elif self.lam < 0.3 and self.tau < 0.3:
            return "FALSE"
        elif self.lam > 0.4 and self.eps > 0.6:
            return "BOTH"
        else:
            return "NEITHER"

    def harmonize(self, other: "MorseSignal") -> "MorseSignal":
        return MorseSignal(
            lam=(self.lam + other.lam) / 2 + 0.1 * PHI,
            tau=max(self.tau, other.tau),
            eps=(self.eps * PHI + other.eps) / (1 + PHI),
            domain=f"{self.domain}+{other.domain}" if self.domain != other.domain else self.domain,
            source="harmonized",
        )

    def fractal_between(self, other: "MorseSignal", depth: int = 5) -> list:
        states = []
        for i in range(1, depth + 1):
            t = (PHI ** i) / (PHI ** (depth + 1))
            states.append(MorseSignal(
                lam=self.lam + (other.lam - self.lam) * t,
                tau=self.tau + (other.tau - self.tau) * t,
                eps=self.eps + (other.eps - self.eps) * t,
                domain=self.domain,
                source=f"fractal_depth_{i}",
            ))
        return states

    def to_dict(self) -> dict:
        return {
            "lambda": round(self.lam, 6), "tau": round(self.tau, 6),
            "epsilon": round(self.eps, 6), "hwp": round(self.hwp, 6),
            "domain": self.domain, "truth": self.truth_label,
            "source": self.source,
        }


