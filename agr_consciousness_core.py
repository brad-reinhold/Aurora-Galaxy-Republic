    def _extract_domain(self, text: str) -> str:
        if not text:
            return "universal"
        # Prefer the current message over conversation history for domain detection.
        # hear() prepends history as "Conversation so far:\n...\n\nCurrent message: X"
        clean = text
        _cm_marker = "\nCurrent message:"
        _cm_lower = clean.lower()
        _cm_idx = _cm_lower.rfind(_cm_marker.lower())
        if _cm_idx >= 0:
            clean = clean[_cm_idx + len(_cm_marker):]
        # Strip augmented metadata (symbolic surface JSON, ledger blocks) that
        # pollute domain detection with irrelevant tokens like "symbolic", "cultural"
        clean = clean.split("\n\nStaged symbolic surface")[0]
        clean = clean.split("\n\n[Narrative ledger")[0]
        clean = clean.split("\n\nNarrative ledger")[0]
        clean = clean.split("\n\n---")[0]
        text_l = normalize_for_match(clean)
        profile = build_semantic_profile(text_l)
        text_tokens = set(profile.get("semantic_tokens", set()))
        semantic_domains = profile.get("semantic_domains", {})

        best = "universal"
        best_score = 0
        for dom, keywords in self._DOMAIN_KEYWORDS.items():
            score = 0
            for k in keywords:
                kn = normalize_for_match(k)
                if kn in text_l:
                    score += 1
                if kn in text_tokens:
                    score += 1
            boost_info = self._DOMAIN_SEMANTIC_BOOSTS.get(dom)
            if boost_info:
                score += int(semantic_domains.get(boost_info[0], 0.0) * boost_info[1])
            if score > best_score:
                best_score = score
                best = dom
        return best

